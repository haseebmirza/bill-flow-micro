import io
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.models.invoice import Invoice


class PDFService:
    @staticmethod
    def generate_invoice_pdf(invoice: Invoice) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=A4, topMargin=30 * mm, bottomMargin=20 * mm)
        styles = getSampleStyleSheet()
        elements = []

        title_style = ParagraphStyle("Title", parent=styles["Title"], fontSize=24, spaceAfter=10)
        elements.append(Paragraph("INVOICE", title_style))
        elements.append(Spacer(1, 5 * mm))

        meta_data = [
            ["Invoice Number:", invoice.invoice_number],
            ["Date:", invoice.issued_at.strftime("%Y-%m-%d")],
            ["Status:", invoice.status.value.upper()],
        ]
        meta_table = Table(meta_data, colWidths=[120, 300])
        meta_table.setStyle(TableStyle([
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
        ]))
        elements.append(meta_table)
        elements.append(Spacer(1, 8 * mm))

        elements.append(Paragraph("Bill To:", styles["Heading3"]))
        elements.append(Paragraph(invoice.customer_name, styles["Normal"]))
        elements.append(Paragraph(invoice.customer_email, styles["Normal"]))
        elements.append(Spacer(1, 8 * mm))

        currency = invoice.currency
        line_items = [
            ["Description", "Amount"],
            ["Payment", f"{currency} {invoice.amount / 100:.2f}"],
            [f"Tax ({float(invoice.tax_rate) * 100:.0f}%)", f"{currency} {invoice.tax_amount / 100:.2f}"],
            ["Total", f"{currency} {invoice.total / 100:.2f}"],
        ]
        items_table = Table(line_items, colWidths=[350, 120])
        items_table.setStyle(TableStyle([
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 10),
            ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f3f4f6")),
            ("BACKGROUND", (0, -1), (-1, -1), colors.HexColor("#f3f4f6")),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("ALIGN", (1, 0), (1, -1), "RIGHT"),
        ]))
        elements.append(items_table)
        elements.append(Spacer(1, 15 * mm))

        footer_style = ParagraphStyle("Footer", parent=styles["Normal"], fontSize=8, textColor=colors.grey)
        elements.append(Paragraph(
            f"Generated by BillFlow Invoice Service",
            footer_style,
        ))

        doc.build(elements)
        return buffer.getvalue()
